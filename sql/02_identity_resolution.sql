-- 02_identity_resolution.sql
-- In-database identity resolution pipeline: unified touchpoints and candidate blocking

OPEN SCHEMA REGRET_RADAR;

-- 1. Unified Touchpoints View across Web, App, POS, and Marketplace
CREATE OR REPLACE VIEW UNIFIED_TOUCHPOINTS AS
SELECT 
    WEB_USER_ID AS TOUCHPOINT_ID,
    CUSTOMER_ID AS TRUE_CUSTOMER_ID,
    'Web' AS CHANNEL,
    FULL_NAME AS RAW_NAME,
    TRIM(LOWER(REGEXP_REPLACE(FULL_NAME, '[^a-zA-Z ]', ''))) AS CLEAN_NAME,
    RIGHT(REGEXP_REPLACE(PHONE, '[^0-9]', ''), 10) AS PHONE_NORM,
    EMAIL,
    SUBSTR(EMAIL, 1, INSTR(EMAIL, '@') - 1) AS EMAIL_PREFIX,
    SUBSTR(EMAIL, INSTR(EMAIL, '@') + 1) AS EMAIL_DOMAIN,
    LEFT(TRIM(FULL_NAME), 4) AS NAME_PREFIX,
    SOUNDEX(FULL_NAME) AS SOUNDEX_NAME,
    CAST(NULL AS VARCHAR(10)) AS PINCODE
FROM WEB_USERS
UNION ALL
SELECT 
    APP_USER_ID AS TOUCHPOINT_ID,
    CUSTOMER_ID AS TRUE_CUSTOMER_ID,
    'App' AS CHANNEL,
    USER_NAME AS RAW_NAME,
    TRIM(LOWER(REGEXP_REPLACE(USER_NAME, '[^a-zA-Z ]', ''))) AS CLEAN_NAME,
    RIGHT(REGEXP_REPLACE(PHONE_NORMALIZED, '[^0-9]', ''), 10) AS PHONE_NORM,
    CAST(NULL AS VARCHAR(100)) AS EMAIL,
    CAST(NULL AS VARCHAR(50)) AS EMAIL_PREFIX,
    CAST(NULL AS VARCHAR(50)) AS EMAIL_DOMAIN,
    LEFT(TRIM(USER_NAME), 4) AS NAME_PREFIX,
    SOUNDEX(USER_NAME) AS SOUNDEX_NAME,
    CAST(NULL AS VARCHAR(10)) AS PINCODE
FROM APP_USERS
UNION ALL
SELECT 
    LOYALTY_CARD_NO AS TOUCHPOINT_ID,
    CUSTOMER_ID AS TRUE_CUSTOMER_ID,
    'POS' AS CHANNEL,
    MEMBER_NAME AS RAW_NAME,
    TRIM(LOWER(REGEXP_REPLACE(MEMBER_NAME, '[^a-zA-Z ]', ''))) AS CLEAN_NAME,
    RIGHT(REGEXP_REPLACE(REGISTERED_PHONE, '[^0-9]', ''), 10) AS PHONE_NORM,
    CAST(NULL AS VARCHAR(100)) AS EMAIL,
    CAST(NULL AS VARCHAR(50)) AS EMAIL_PREFIX,
    CAST(NULL AS VARCHAR(50)) AS EMAIL_DOMAIN,
    LEFT(TRIM(MEMBER_NAME), 4) AS NAME_PREFIX,
    SOUNDEX(MEMBER_NAME) AS SOUNDEX_NAME,
    PINCODE
FROM POS_LOYALTY
UNION ALL
SELECT 
    MARKETPLACE_BUYER_ID AS TOUCHPOINT_ID,
    CUSTOMER_ID AS TRUE_CUSTOMER_ID,
    'Marketplace' AS CHANNEL,
    BUYER_ALIAS AS RAW_NAME,
    TRIM(LOWER(REGEXP_REPLACE(BUYER_ALIAS, '[^a-zA-Z ]', ''))) AS CLEAN_NAME,
    RIGHT(REGEXP_REPLACE(MASKED_PHONE, '[^0-9]', ''), 4) AS PHONE_NORM,
    CAST(NULL AS VARCHAR(100)) AS EMAIL,
    CAST(NULL AS VARCHAR(50)) AS EMAIL_PREFIX,
    CAST(NULL AS VARCHAR(50)) AS EMAIL_DOMAIN,
    LEFT(TRIM(BUYER_ALIAS), 4) AS NAME_PREFIX,
    SOUNDEX(BUYER_ALIAS) AS SOUNDEX_NAME,
    SHIPPING_PINCODE AS PINCODE
FROM MARKETPLACE_BUYERS;

-- 2. SQL Blocking View for Candidate Pair Generation
CREATE OR REPLACE VIEW CANDIDATE_PAIRS AS
SELECT DISTINCT
    MOD(ASCII(SUBSTR(a.TOUCHPOINT_ID, 1, 1)) + ASCII(SUBSTR(b.TOUCHPOINT_ID, 1, 1)), 8) AS BLOCK_ID,
    a.TOUCHPOINT_ID AS ID1,
    a.RAW_NAME AS NAME1,
    a.EMAIL AS EMAIL1,
    a.PHONE_NORM AS PHONE1,
    a.PINCODE AS ADDR1,
    b.TOUCHPOINT_ID AS ID2,
    b.RAW_NAME AS NAME2,
    b.EMAIL AS EMAIL2,
    b.PHONE_NORM AS PHONE2,
    b.PINCODE AS ADDR2
FROM UNIFIED_TOUCHPOINTS a
JOIN UNIFIED_TOUCHPOINTS b 
  ON a.TOUCHPOINT_ID < b.TOUCHPOINT_ID
WHERE 
    -- Block 1: Exact 10-digit phone
    (LENGTH(a.PHONE_NORM) = 10 AND a.PHONE_NORM = b.PHONE_NORM)
    OR
    -- Block 2: Email prefix
    (a.EMAIL_PREFIX IS NOT NULL AND a.EMAIL_PREFIX = b.EMAIL_PREFIX)
    OR
    -- Block 3: Exact cleaned full name
    (LENGTH(a.CLEAN_NAME) > 6 AND a.CLEAN_NAME = b.CLEAN_NAME)
    OR
    -- Block 4: Masked phone (last 4 digits) + matching Pincode
    (LENGTH(a.PHONE_NORM) = 4 AND LENGTH(b.PHONE_NORM) = 10 AND RIGHT(b.PHONE_NORM, 4) = a.PHONE_NORM AND a.PINCODE = b.PINCODE)
    OR
    -- Block 5: Near phone (9 digits match)
    (LENGTH(a.PHONE_NORM) = 10 AND LENGTH(b.PHONE_NORM) = 10 AND LEFT(a.PHONE_NORM, 9) = LEFT(b.PHONE_NORM, 9));
