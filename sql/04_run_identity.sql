-- 04_run_identity.sql
-- Materialize matched candidate pairs and resolved customer identity graph

OPEN SCHEMA REGRET_RADAR;

-- 1. Score candidate pairs using SET-EMITS Python UDF
CREATE OR REPLACE TABLE MATCHED_PAIRS AS
SELECT SCORE_IDENTITY_PAIRS(
    BLOCK_ID, ID1, NAME1, EMAIL1, PHONE1, ADDR1,
    ID2, NAME2, EMAIL2, PHONE2, ADDR2
)
FROM CANDIDATE_PAIRS
GROUP BY BLOCK_ID;

-- 2. Clustered Touchpoints using Connected Components UDF
CREATE OR REPLACE TABLE CLUSTERED_TOUCHPOINTS AS
SELECT RESOLVE_CONNECTED_COMPONENTS(grp, ID1, ID2)
FROM (SELECT 1 AS grp, ID1, ID2 FROM MATCHED_PAIRS)
GROUP BY grp;

-- 3. Final Customer Identity Graph combining clusters and singletons
CREATE OR REPLACE TABLE CUSTOMER_IDENTITY_GRAPH AS
SELECT 
    t.TOUCHPOINT_ID,
    t.TRUE_CUSTOMER_ID,
    t.CHANNEL,
    COALESCE(c.GOLDEN_CUSTOMER_ID, 'GOLD_' || t.TOUCHPOINT_ID) AS GOLDEN_CUSTOMER_ID,
    COALESCE(c.CLUSTER_SIZE, 1) AS CLUSTER_SIZE
FROM UNIFIED_TOUCHPOINTS t
LEFT JOIN CLUSTERED_TOUCHPOINTS c ON t.TOUCHPOINT_ID = c.TOUCHPOINT_ID;
