-- 01_schema.sql
-- Idempotent schema and table definitions for Regret Radar

CREATE SCHEMA IF NOT EXISTS REGRET_RADAR;
OPEN SCHEMA REGRET_RADAR;

-- 1. Ground Truth Customer Directory
CREATE TABLE IF NOT EXISTS CUSTOMERS_TRUE (
    CUSTOMER_ID VARCHAR(20) PRIMARY KEY,
    FIRST_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50),
    EMAIL VARCHAR(100),
    PHONE VARCHAR(20),
    CITY VARCHAR(50),
    "STATE" VARCHAR(50),
    PINCODE VARCHAR(10)
);

-- 2. Web Users Touchpoint
CREATE TABLE IF NOT EXISTS WEB_USERS (
    WEB_USER_ID VARCHAR(20) PRIMARY KEY,
    CUSTOMER_ID VARCHAR(20),
    EMAIL VARCHAR(100),
    PHONE VARCHAR(20),
    FULL_NAME VARCHAR(100),
    COOKIE_ID VARCHAR(50)
);

-- 3. App Users Touchpoint
CREATE TABLE IF NOT EXISTS APP_USERS (
    APP_USER_ID VARCHAR(20) PRIMARY KEY,
    CUSTOMER_ID VARCHAR(20),
    DEVICE_ID VARCHAR(50),
    PHONE_NORMALIZED VARCHAR(20),
    USER_NAME VARCHAR(100)
);

-- 4. POS Loyalty Touchpoint
CREATE TABLE IF NOT EXISTS POS_LOYALTY (
    LOYALTY_CARD_NO VARCHAR(20) PRIMARY KEY,
    CUSTOMER_ID VARCHAR(20),
    MEMBER_NAME VARCHAR(100),
    REGISTERED_PHONE VARCHAR(20),
    PINCODE VARCHAR(10)
);

-- 5. Marketplace Touchpoint
CREATE TABLE IF NOT EXISTS MARKETPLACE_BUYERS (
    MARKETPLACE_BUYER_ID VARCHAR(20) PRIMARY KEY,
    CUSTOMER_ID VARCHAR(20),
    PLATFORM VARCHAR(30),
    BUYER_ALIAS VARCHAR(100),
    MASKED_PHONE VARCHAR(20),
    SHIPPING_PINCODE VARCHAR(10)
);

-- 6. Products Catalog
CREATE TABLE IF NOT EXISTS PRODUCTS (
    SKU_ID VARCHAR(20) PRIMARY KEY,
    PRODUCT_NAME VARCHAR(150),
    CATEGORY VARCHAR(50),
    SIZE VARCHAR(20),
    COST_PRICE_INR DECIMAL(12,2),
    MRP_INR DECIMAL(12,2),
    BASE_RETURN_RISK DECIMAL(5,4)
);

-- 7. Stores Catalog
CREATE TABLE IF NOT EXISTS STORES (
    STORE_ID VARCHAR(20) PRIMARY KEY,
    STORE_NAME VARCHAR(100),
    CITY VARCHAR(50),
    "STATE" VARCHAR(50),
    CHANNEL_TYPE VARCHAR(30)
);

-- 8. Orders Header
CREATE TABLE IF NOT EXISTS ORDERS (
    ORDER_ID VARCHAR(20) PRIMARY KEY,
    CUSTOMER_ID VARCHAR(20),
    STORE_ID VARCHAR(20),
    CHANNEL VARCHAR(20),
    ORDER_DATE DATE,
    TOTAL_AMOUNT_INR DECIMAL(12,2)
);

-- 9. Order Items Detail
CREATE TABLE IF NOT EXISTS ORDER_ITEMS (
    ORDER_ITEM_ID VARCHAR(20) PRIMARY KEY,
    ORDER_ID VARCHAR(20),
    SKU_ID VARCHAR(20),
    QUANTITY INT,
    UNIT_PRICE_INR DECIMAL(12,2),
    DISCOUNT_INR DECIMAL(12,2),
    LINE_TOTAL_INR DECIMAL(12,2)
);

-- 10. Product Returns
CREATE TABLE IF NOT EXISTS "RETURNS" (
    RETURN_ID VARCHAR(20) PRIMARY KEY,
    ORDER_ITEM_ID VARCHAR(20),
    ORDER_ID VARCHAR(20),
    SKU_ID VARCHAR(20),
    CUSTOMER_ID VARCHAR(20),
    RETURN_DATE DATE,
    RETURN_REASON VARCHAR(100),
    REFUND_AMOUNT_INR DECIMAL(12,2)
);

-- 11. Daily Store Inventory & Stockouts
CREATE TABLE IF NOT EXISTS DAILY_INVENTORY (
    INVENTORY_DATE DATE,
    STORE_ID VARCHAR(20),
    SKU_ID VARCHAR(20),
    BEGINNING_STOCK INT,
    UNITS_RECEIVED INT,
    UNITS_SOLD INT,
    ENDING_STOCK INT,
    IS_STOCKOUT INT,
    MISSED_DEMAND_UNITS INT
);

-- 12. Support Tickets with Sentiment & Churn Keywords
CREATE TABLE IF NOT EXISTS SUPPORT_TICKETS (
    TICKET_ID VARCHAR(20) PRIMARY KEY,
    CUSTOMER_ID VARCHAR(20),
    CREATED_AT DATE,
    SUBJECT VARCHAR(100),
    TICKET_TEXT VARCHAR(1000),
    SENTIMENT VARCHAR(20),
    CHURN_INTENT_FLAG INT
);

-- 13. Ground Truth Churn Labels
CREATE TABLE IF NOT EXISTS CHURN_LABELS (
    CUSTOMER_ID VARCHAR(20) PRIMARY KEY,
    CHURNED INT,
    CHURN_DATE DATE,
    CHURN_RISK_SCORE DECIMAL(4,2),
    IS_HIGH_RISK_COHORT INT
);
