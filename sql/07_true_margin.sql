-- 07_true_margin.sql
-- True Margin accounting view and ranked margin erosion analysis

OPEN SCHEMA REGRET_RADAR;

-- 1. Order Item Level True Margin View
-- True Margin = Price - COGS - Return Logistics (₹150/return) - Write-off (20% of COGS)
CREATE OR REPLACE VIEW V_TRUE_MARGIN AS
WITH SCORED_ITEMS AS (
    SELECT
        i.ORDER_ITEM_ID,
        i.ORDER_ID,
        i.SKU_ID,
        o.CUSTOMER_ID,
        o.ORDER_DATE,
        o.CHANNEL,
        p.PRODUCT_NAME,
        p.CATEGORY,
        p.SIZE,
        i.QUANTITY,
        i.UNIT_PRICE_INR,
        i.DISCOUNT_INR,
        i.LINE_TOTAL_INR AS REVENUE_INR,
        (i.QUANTITY * p.COST_PRICE_INR) AS COGS_INR,
        (i.LINE_TOTAL_INR - (i.QUANTITY * p.COST_PRICE_INR)) AS NOMINAL_MARGIN_INR,
        SCORE_RETURN_PROBABILITY(
            p.CATEGORY,
            p.SIZE,
            o.CHANNEL,
            CAST(i.UNIT_PRICE_INR AS DOUBLE),
            CAST(i.DISCOUNT_INR AS DOUBLE),
            CAST(i.QUANTITY AS DOUBLE),
            CAST(p.COST_PRICE_INR AS DOUBLE)
        ) AS RETURN_PROBABILITY
    FROM ORDER_ITEMS i
    JOIN ORDERS o ON i.ORDER_ID = o.ORDER_ID
    JOIN PRODUCTS p ON i.SKU_ID = p.SKU_ID
)
SELECT
    ORDER_ITEM_ID,
    ORDER_ID,
    SKU_ID,
    CUSTOMER_ID,
    ORDER_DATE,
    CHANNEL,
    PRODUCT_NAME,
    CATEGORY,
    SIZE,
    QUANTITY,
    UNIT_PRICE_INR,
    DISCOUNT_INR,
    REVENUE_INR,
    COGS_INR,
    NOMINAL_MARGIN_INR,
    RETURN_PROBABILITY,
    ROUND(RETURN_PROBABILITY * 150.0, 2) AS RETURN_LOGISTICS_INR,
    ROUND(RETURN_PROBABILITY * 0.20 * COGS_INR, 2) AS WRITE_OFF_INR,
    ROUND(NOMINAL_MARGIN_INR - (RETURN_PROBABILITY * 150.0) - (RETURN_PROBABILITY * 0.20 * COGS_INR), 2) AS TRUE_MARGIN_INR,
    ROUND((RETURN_PROBABILITY * 150.0) + (RETURN_PROBABILITY * 0.20 * COGS_INR), 2) AS MARGIN_EROSION_INR
FROM SCORED_ITEMS;

-- 2. Materialized Order Item True Margins Table for High-Performance Queries
CREATE TABLE IF NOT EXISTS ORDER_ITEM_MARGINS (
    ORDER_ITEM_ID VARCHAR(20) PRIMARY KEY,
    ORDER_ID VARCHAR(20),
    SKU_ID VARCHAR(20),
    CUSTOMER_ID VARCHAR(20),
    ORDER_DATE DATE,
    CHANNEL VARCHAR(20),
    PRODUCT_NAME VARCHAR(150),
    CATEGORY VARCHAR(50),
    SIZE VARCHAR(20),
    QUANTITY INT,
    UNIT_PRICE_INR DECIMAL(12,2),
    DISCOUNT_INR DECIMAL(12,2),
    REVENUE_INR DECIMAL(12,2),
    COGS_INR DECIMAL(12,2),
    NOMINAL_MARGIN_INR DECIMAL(12,2),
    RETURN_PROBABILITY DOUBLE,
    RETURN_LOGISTICS_INR DECIMAL(12,2),
    WRITE_OFF_INR DECIMAL(12,2),
    TRUE_MARGIN_INR DECIMAL(12,2),
    MARGIN_EROSION_INR DECIMAL(12,2)
);

-- 3. Ranked Products with the Biggest Margin Erosion View
CREATE OR REPLACE VIEW RANKED_PRODUCTS_MARGIN_EROSION AS
SELECT
    SKU_ID,
    PRODUCT_NAME,
    CATEGORY,
    SIZE,
    COUNT(ORDER_ITEM_ID) AS ORDER_COUNT,
    SUM(QUANTITY) AS TOTAL_UNITS_SOLD,
    SUM(REVENUE_INR) AS TOTAL_REVENUE_INR,
    SUM(COGS_INR) AS TOTAL_COGS_INR,
    SUM(NOMINAL_MARGIN_INR) AS TOTAL_NOMINAL_MARGIN_INR,
    ROUND(SUM(RETURN_PROBABILITY), 1) AS EXPECTED_RETURNS,
    SUM(RETURN_LOGISTICS_INR) AS TOTAL_RETURN_LOGISTICS_INR,
    SUM(WRITE_OFF_INR) AS TOTAL_WRITE_OFF_INR,
    SUM(TRUE_MARGIN_INR) AS TOTAL_TRUE_MARGIN_INR,
    SUM(MARGIN_EROSION_INR) AS TOTAL_MARGIN_EROSION_INR,
    ROUND(SUM(MARGIN_EROSION_INR) / NULLIF(SUM(NOMINAL_MARGIN_INR), 0) * 100, 2) AS MARGIN_EROSION_PCT
FROM ORDER_ITEM_MARGINS
GROUP BY SKU_ID, PRODUCT_NAME, CATEGORY, SIZE
ORDER BY TOTAL_MARGIN_EROSION_INR DESC;

-- 4. Ranked Orders with the Biggest Margin Erosion View
CREATE OR REPLACE VIEW RANKED_ORDERS_MARGIN_EROSION AS
SELECT
    ORDER_ID,
    CUSTOMER_ID,
    ORDER_DATE,
    CHANNEL,
    COUNT(ORDER_ITEM_ID) AS ITEM_COUNT,
    SUM(QUANTITY) AS TOTAL_QUANTITY,
    SUM(REVENUE_INR) AS ORDER_TOTAL_INR,
    SUM(NOMINAL_MARGIN_INR) AS ORDER_NOMINAL_MARGIN_INR,
    ROUND(SUM(RETURN_PROBABILITY), 2) AS EXPECTED_RETURNS,
    SUM(RETURN_LOGISTICS_INR) AS ORDER_RETURN_LOGISTICS_INR,
    SUM(WRITE_OFF_INR) AS ORDER_WRITE_OFF_INR,
    SUM(TRUE_MARGIN_INR) AS ORDER_TRUE_MARGIN_INR,
    SUM(MARGIN_EROSION_INR) AS ORDER_MARGIN_EROSION_INR,
    ROUND(SUM(MARGIN_EROSION_INR) / NULLIF(SUM(NOMINAL_MARGIN_INR), 0) * 100, 2) AS MARGIN_EROSION_PCT
FROM ORDER_ITEM_MARGINS
GROUP BY ORDER_ID, CUSTOMER_ID, ORDER_DATE, CHANNEL
ORDER BY ORDER_MARGIN_EROSION_INR DESC;
